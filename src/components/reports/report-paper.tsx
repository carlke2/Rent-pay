import type { Block, Cell, Column, ReportDocument, Row, Table } from "@/reports/document";
import { kes, plain } from "@/reports/document";
import "./report-paper.css";

/** One report on white A4 paper: the same markup on screen (inside the admin page) and in the PDF (print) view. */
export function ReportPaper({ document }: { document: ReportDocument }) {
  return (
    <article className="rp-paper" aria-label={document.title}>
      <header className="rp-header">
        <div className="rp-owner">
          <img src="/brand/logo-light.svg" alt="RentPay" className="rp-logo" width={120} height={29} />
          <p className="rp-owner-name">{document.landlord.name}</p>
          <p>Paybill {document.landlord.paybill}</p>
          {document.landlord.email ? <p>{document.landlord.email}</p> : null}
        </div>
        <div className="rp-heading">
          <p className="rp-kind">{document.kind}</p>
          <h1 className="rp-title">{document.title}</h1>
          <p className="rp-period">
            {document.period} · {document.filter}
          </p>
          <p className="rp-generated">
            Generated {document.generatedLabel} · {document.number}
          </p>
        </div>
      </header>
      {document.note ? <p className="rp-note rp-lead">{document.note}</p> : null}

      <section className="rp-summary" aria-label="Summary">
        {document.summary.map((box, index) => (
          <div key={box.label} className={index === 0 ? "rp-box rp-box-lead" : "rp-box"}>
            <p className="rp-box-label">{box.label}</p>
            <p className="rp-box-value">{box.value}</p>
            <p className="rp-box-note">{box.note}</p>
          </div>
        ))}
      </section>

      {document.sections.map((section) => (
        <section key={section.id} className="rp-section">
          {section.title ? <h2 className="rp-section-title">{section.title}</h2> : null}
          {section.blocks.map((block, index) => (
            <BlockView key={index} block={block} />
          ))}
        </section>
      ))}

      <section className="rp-section rp-closing">
        {document.closing.title ? <h2 className="rp-section-title">{document.closing.title}</h2> : null}
        {document.closing.blocks.map((block, index) => (
          <BlockView key={index} block={block} />
        ))}
      </section>

      <footer className="rp-footer">
        <p>Figures as at {document.generatedLabel} EAT. Amounts in Kenya shillings.</p>
        <p>Generated by RentPay · {document.number}</p>
      </footer>
    </article>
  );
}

function BlockView({ block }: { block: Block }) {
  switch (block.kind) {
    case "table":
      return <TableView table={block.table} />;
    case "pair":
      return (
        <div className="rp-pair">
          {block.tables.map((table) => (
            <TableView key={table.id} table={table} />
          ))}
        </div>
      );
    case "facts":
      return (
        <div className="rp-facts">
          {block.boxes.map((box) => (
            <div key={box.title} className="rp-facts-box">
              <h3>{box.title}</h3>
              <dl>
                {box.facts.map(([label, value]) => (
                  <div key={label}>
                    <dt>{label}</dt>
                    <dd>{value}</dd>
                  </div>
                ))}
              </dl>
            </div>
          ))}
        </div>
      );
    case "calc":
      return (
        <div className={block.aside ? "rp-calc-row" : undefined}>
          <div className={block.large ? "rp-calc rp-calc-large" : "rp-calc"}>
            <dl>
              {block.lines.map((line) => (
                <div key={line.label} className="rp-calc-line">
                  <dt>
                    {line.label}
                    {line.sub ? <span className="rp-sub">{line.sub}</span> : null}
                  </dt>
                  <dd className={line.display ? "rp-calc-display" : undefined}>
                    {line.display ?? (line.amount === null ? "—" : `${line.op === "−" ? "− " : ""}${kes(line.amount)}`)}
                  </dd>
                </div>
              ))}
              <div className="rp-calc-result">
                <dt>{block.result.label}</dt>
                <dd>{kes(block.result.amount, { credit: block.result.credit })}</dd>
              </div>
            </dl>
            {block.notes?.map((note) => (
              <p key={note} className="rp-calc-note">
                {note}
              </p>
            ))}
          </div>
          {block.aside ? (
            <div className="rp-facts-box rp-aside">
              <h3>{block.aside.title}</h3>
              <dl>
                {block.aside.facts.map(([label, value]) => (
                  <div key={label}>
                    <dt>{label}</dt>
                    <dd>{value}</dd>
                  </div>
                ))}
              </dl>
            </div>
          ) : null}
        </div>
      );
    case "bands":
      return (
        <div className="rp-bands">
          <h3>{block.title}</h3>
          <div className="rp-bands-row">
            {block.bands.map((band) => (
              <div key={band.label} className="rp-band">
                <p className="rp-box-label">{band.label}</p>
                <p className="rp-band-value">{band.amount === 0 ? "—" : kes(band.amount, { credit: band.credit })}</p>
              </div>
            ))}
          </div>
        </div>
      );
    case "reconcile":
      return <p className={`rp-reconcile rp-reconcile-${block.status}`}>{block.text}</p>;
    case "note":
      return <p className="rp-note">{block.text}</p>;
    case "signatures":
      return (
        <div className="rp-signatures">
          {block.labels.map((label) => (
            <div key={label} className="rp-signature">
              <div className="rp-signature-line" />
              <p>
                <strong>{label}</strong> · Name, signature and date
              </p>
            </div>
          ))}
        </div>
      );
  }
}

function TableView({ table }: { table: Table }) {
  return (
    <div className="rp-table-block">
      {table.hideTitle ? null : <h3 className="rp-table-title">{table.title}</h3>}
      {table.rows.length === 0 && table.emptyText ? (
        <p className="rp-note">{table.emptyText}</p>
      ) : (
        <div className="rp-scroll">
          <table className="rp-table">
            {table.columns.some((column) => column.width) ? (
              <colgroup>
                {table.columns.map((column) => (
                  <col key={column.key} style={column.width ? { width: column.width } : undefined} />
                ))}
              </colgroup>
            ) : null}
            <thead>
              <tr>
                {table.columns.map((column) => (
                  <th key={column.key} scope="col" className={column.type === "text" ? undefined : "rp-num"}>
                    {column.label}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {table.rows.map((row, index) => (
                <tr key={index}>
                  {table.columns.map((column) => (
                    <CellView key={column.key} column={column} cell={row[column.key]} />
                  ))}
                </tr>
              ))}
            </tbody>
            {table.total ? (
              <tfoot>
                <tr>
                  {/* The label spans the leading text columns that have nothing to total. */}
                  <td colSpan={labelSpan(table)}>{table.total.label}</td>
                  {table.columns.slice(labelSpan(table)).map((column) => (
                    <CellView key={column.key} column={column} cell={(table.total!.cells as Row | undefined)?.[column.key]} total />
                  ))}
                </tr>
              </tfoot>
            ) : null}
          </table>
        </div>
      )}
    </div>
  );
}

function labelSpan(table: Table): number {
  const index = table.columns.findIndex((column, position) => position > 0 && (column.type !== "text" || table.total?.cells?.[column.key]));
  return index === -1 ? table.columns.length : index;
}

/** Codes such as RCT-000058 or WES-B10 stay on one line instead of breaking at the hyphen. */
const isCode = (value: string) => value.length > 0 && value.length <= 14 && !value.includes(" ");

function formatCell(cell: Cell): string {
  if (cell.kind === "count") return cell.value === null ? "—" : plain(cell.value);
  if (cell.kind === "money") {
    if (cell.amount === null) return cell.label ?? "—";
    if (cell.amount < 0) return cell.brackets ? `(${plain(-cell.amount)})` : `−${plain(-cell.amount)}`;
    return plain(cell.amount);
  }
  return cell.text;
}

function CellView({ column, cell, total = false }: { column: Column; cell: Cell | undefined; total?: boolean }) {
  const numeric = column.type !== "text";
  if (!cell) return <td className={numeric ? "rp-num" : undefined}>{total ? "" : "—"}</td>;
  if (cell.kind === "text") {
    return (
      <td className={[numeric ? "rp-num" : "", cell.italic ? "rp-italic" : "", isCode(cell.text) || column.key === "date" ? "rp-nowrap" : ""].join(" ").trim() || undefined}>
        {cell.text}
        {cell.tag ? <span className={`rp-tag rp-tag-${cell.tag.tone}`}>{cell.tag.label}</span> : null}
        {cell.sub ? <span className="rp-sub">{cell.sub}</span> : null}
      </td>
    );
  }
  const tone = cell.kind === "money" && cell.tone && cell.amount ? ` rp-${cell.tone}` : "";
  const muted = cell.kind === "money" && cell.amount === null && cell.label ? " rp-label" : "";
  return (
    <td className={`rp-num${tone}${muted}`}>
      {formatCell(cell)}
      {cell.kind === "money" && cell.sub ? <span className="rp-sub">{cell.sub}</span> : null}
    </td>
  );
}
