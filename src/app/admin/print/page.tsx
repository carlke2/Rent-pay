import type { Metadata } from "next";
import { cache } from "react";
import { requireLandlord } from "@/authentication/roles";
import { PrintReportToolbar } from "@/components/reports/print-report-toolbar";
import { ReportPaper } from "@/components/reports/report-paper";
import { buildReport, isReportSlug, readReportParameters, ReportNeedsInput } from "@/reports";

export const dynamic = "force-dynamic";

type Props = { searchParams: Promise<Record<string, string | string[] | undefined>> };

// Metadata and the page share one build per request.
const buildFromQuery = cache(async (key: string) => {
  const query = JSON.parse(key) as Record<string, string | string[] | undefined>;
  const slug = isReportSlug(query.report) ? query.report : "payments-received";
  return buildReport(slug, readReportParameters(slug, query));
});
const load = async (searchParams: Props["searchParams"]) => buildFromQuery(JSON.stringify(await searchParams));

// The browser names the saved PDF after the page title: rentpay-{report}-{period}.
export async function generateMetadata({ searchParams }: Props): Promise<Metadata> {
  await requireLandlord();
  try {
    return { title: { absolute: (await load(searchParams)).fileName } };
  } catch {
    return { title: "Report" };
  }
}

/**
 * The PDF view of a report: the same paper as on screen, alone on the page, printed by the browser's PDF engine
 * on A4 with 18 mm margins, page numbers and the table header repeated on each page.
 */
export default async function PrintReportPage({ searchParams }: Props) {
  await requireLandlord();
  const query = await searchParams;
  let document;
  try {
    document = await load(searchParams);
  } catch (error) {
    if (error instanceof ReportNeedsInput) return <p style={{ padding: 24 }}>{error.message}</p>;
    throw error;
  }
  const footer = `Generated by RentPay · ${document.number}`.replace(/["\\]/g, "");
  return (
    <>
      <style>{`
        @page {
          size: A4;
          margin: 18mm;
          @bottom-left { content: "${footer}"; font: 8pt system-ui, sans-serif; color: #52525b; }
          @bottom-right { content: "Page " counter(page) " of " counter(pages); font: 8pt system-ui, sans-serif; color: #52525b; }
        }
        html, body { background: #fff !important; color-scheme: light; }
        @media screen { body { background: #d4d4d8 !important; } .rp-print-main { padding: 24px 16px 48px; } }
      `}</style>
      <PrintReportToolbar fileName={document.fileName} auto={query.auto === "1"} />
      <main className="rp-print-main">
        <ReportPaper document={document} />
      </main>
    </>
  );
}
